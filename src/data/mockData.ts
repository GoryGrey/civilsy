function makeTownship(
  slug: string,
  name: string,
  population: string,
  address: string,
  schedule: string,
  zipCodes: string[],
  schoolDistrict: string,
  portalUrl = 'https://www.ashtabulacounty.us/townships'
): Community {
  return {
    id: `${slug}-twp-oh`,
    name: `${name} Township`,
    kind: 'Township',
    state: 'Ohio',
    population,
    executiveTitle: 'Board of Township Trustees',
    executiveName: '3 Elected Trustees & Fiscal Officer',
    councilType: 'Township Trustees (At-Large)',
    cityHallAddress: address,
    councilMeetingSchedule: schedule,
    activeIssuesCount: 3,
    officialPortalUrl: portalUrl,
    zipCodes,
    schoolDistrict,
  };
}

